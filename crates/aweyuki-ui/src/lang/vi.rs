//! Vietnamese for the text the pages write. Where two places write the
//! same English words for different Chinese meanings, the Chinese text
//! settles which meaning is meant; a page that has no translation yet
//! falls back to its English text.

/// The Vietnamese text for `(hans, en)`, or `en` where none is written.
pub fn text(hans: &'static str, en: &'static str) -> &'static str {
    match lookup(hans, en) {
        Some(vi) => vi,
        _ => en,
    }
}

